        "manual",[1.684,1.665], ...
        [100,100],[100,100],[5*pi*2,5*pi*3],[],1.20);

    expectedCourseStressMPa = [ ...
        30.360058071, ...
        21.428431237, ...
        178.364310733, ...
        126.648446659];

    actualCourseStressMPa = [ ...
        courseCase.stressDriveMPa(1), ...
        courseCase.stressDrivenMPa(1), ...
        courseCase.stressDriveMPa(2), ...
        courseCase.stressDrivenMPa(2)];

    testName(2) = "Kursusopgave: fire tandfodsspaendinger";

    testPassed(2) = ...
        max(abs(actualCourseStressMPa - ...
        expectedCourseStressMPa)) < 1e-8;

    testDetail(2) = sprintf([ ...
        'sigma=[%.1f, %.1f, %.0f, %.0f] MPa'], ...
        actualCourseStressMPa);

    % Test 3: Qv=12 skal give B=0 og Kv=1.
    qualityLimitCase = calculateT3SpurGear( ...
        20,40,2,20,12, ...
        "force",NaN,2000, ...
        "velocity",NaN,100, ...
        "calculate",NaN, ...
        100,100,30,[],1.20);

    testName(3) = "Randtilfaelde: Qv=12 giver Kv=1";

    testPassed(3) = ...
        abs(qualityLimitCase.dynamicParameterB) < 1e-12 && ...
        abs(qualityLimitCase.dynamicFactorKv - 1) < 1e-12;

    testDetail(3) = sprintf( ...
        'B=%.3g, Kv=%.6f', ...
        qualityLimitCase.dynamicParameterB, ...
        qualityLimitCase.dynamicFactorKv);

    % Test 4: 28 mm er mindre end eksamenskravet 28.412 mm.
    failureCase = calculateT3SpurGear( ...
        20,40,2,20,5, ...
        "torque",40,NaN, ...
        "rpm",3000,NaN, ...
        "calculate",NaN, ...
        100,100,28,[],1.20);

    testName(4) = "Fejltilfaelde: b=28 mm er for lille";

    testPassed(4) = ...
        ~failureCase.stageWidthOK && ...
        failureCase.stressDriveMPa > 100 && ...
        ~failureCase.allProvidedWidthsOK;

    testDetail(4) = sprintf([ ...
        'sigma_pinion=%.2f MPa, status=%s'], ...
        failureCase.stressDriveMPa, ...
        char(failureCase.stageStatus));

    testTable = table( ...
        testName,testPassed,testDetail, ...
        'VariableNames',{'Test','Passed','Detail'});

    disp('Indbyggede regressionstests:')
    disp(testTable)

    results.courseTests = testTable;

    if all(testPassed)
        fprintf('OK - alle fire indbyggede tests bestod.\n');
    else
        error('T3:RegressionTestFailed', ...
            'Mindst én indbygget regressionstest fejlede.');
    end
end

%% LOCAL FUNCTIONS
function out = calculateT3SpurGear( ...
    zDrive, ...
    zDriven, ...
    moduleStageMM, ...
    pressureAngleDeg, ...
    qualityNumberQv, ...
    loadInputMode, ...
    driveTorqueNm, ...
    tangentialForceNInput, ...
    speedInputMode, ...
    driveSpeedRPM, ...
    pitchLineVelocityInputMPerSec, ...
    contactRatioMode, ...
    manualContactRatio, ...
    allowableStressDriveMPa, ...
    allowableStressDrivenMPa, ...
    faceWidthStageMM, ...
    availableStandardFaceWidthsMM, ...
    minimumContactRatio)

    zDrive = zDrive(:).';
    zDriven = zDriven(:).';
    moduleStageMM = moduleStageMM(:).';
    pressureAngleDeg = pressureAngleDeg(:).';
    qualityNumberQv = qualityNumberQv(:).';
    driveTorqueNm = driveTorqueNm(:).';
    tangentialForceNInput = tangentialForceNInput(:).';
    driveSpeedRPM = driveSpeedRPM(:).';
    pitchLineVelocityInputMPerSec = ...
        pitchLineVelocityInputMPerSec(:).';
    manualContactRatio = manualContactRatio(:).';
    allowableStressDriveMPa = allowableStressDriveMPa(:).';
    allowableStressDrivenMPa = allowableStressDrivenMPa(:).';
    faceWidthStageMM = faceWidthStageMM(:).';
    availableStandardFaceWidthsMM = ...
        sort(unique(availableStandardFaceWidthsMM(:).'));

    numberOfStages = numel(zDrive);

    drivePitchDiameterMM = ...
        zDrive .* moduleStageMM;

    drivenPitchDiameterMM = ...
        zDriven .* moduleStageMM;

    stageRatio = ...
        zDriven ./ zDrive;

    driveAddendumDiameterMM = ...
        drivePitchDiameterMM + 2*moduleStageMM;

    drivenAddendumDiameterMM = ...
        drivenPitchDiameterMM + 2*moduleStageMM;

    driveBaseDiameterMM = ...
        drivePitchDiameterMM .* cosd(pressureAngleDeg);

    drivenBaseDiameterMM = ...
        drivenPitchDiameterMM .* cosd(pressureAngleDeg);

    centerDistanceMM = 0.5*( ...
        drivePitchDiameterMM + drivenPitchDiameterMM);

    driveRadicand = ...
        driveAddendumDiameterMM.^2 - driveBaseDiameterMM.^2;

    drivenRadicand = ...
        drivenAddendumDiameterMM.^2 - drivenBaseDiameterMM.^2;

    if any(driveRadicand < -1e-10) || ...
       any(drivenRadicand < -1e-10)
        error('T3:ImpossibleGeometry', ...
            'Tandtopcirklen ligger inden for grundcirklen.');
    end

    driveRadicand = max(driveRadicand,0);
    drivenRadicand = max(drivenRadicand,0);

    pathOfContactMM = 0.5*( ...
        sqrt(driveRadicand) + sqrt(drivenRadicand)) - ...
        centerDistanceMM .* sind(pressureAngleDeg);

    basePitchMM = ...
        pi*moduleStageMM.*cosd(pressureAngleDeg);

    contactRatioCalculated = ...
        pathOfContactMM ./ basePitchMM;

    if strcmpi(contactRatioMode,"calculate")
        contactRatioUsed = contactRatioCalculated;
        contactRatioSource = ...
            repmat("Beregnet standardgeometri",numberOfStages,1);
    else
        contactRatioUsed = manualContactRatio;
        contactRatioSource = ...
            repmat("Manuelt input",numberOfStages,1);
    end

    contactFactorKe = ...
        1 ./ contactRatioUsed;

    if strcmpi(loadInputMode,"torque")
        tangentialForceN = ...
            2*driveTorqueNm*1000 ./ drivePitchDiameterMM;

        equivalentDriveTorqueNm = ...
            driveTorqueNm;
    else
        tangentialForceN = ...
            tangentialForceNInput;

        equivalentDriveTorqueNm = ...
            tangentialForceN .* drivePitchDiameterMM / 2000;
    end

    if strcmpi(speedInputMode,"rpm")
        driveOmegaRadPerSec = ...
            driveSpeedRPM*2*pi/60;

        pitchLineVelocityMPerSec = ...
            drivePitchDiameterMM/2000 .* driveOmegaRadPerSec;
    else
        pitchLineVelocityMPerSec = ...
            pitchLineVelocityInputMPerSec;

        driveOmegaRadPerSec = ...
            2*pitchLineVelocityMPerSec ./ ...
            (drivePitchDiameterMM/1000);

        driveSpeedRPM = ...
            driveOmegaRadPerSec*60/(2*pi);
    end

    dynamicParameterB = ...
        0.25*(12-qualityNumberQv).^(2/3);

    dynamicParameterA = ...
        50 + 56*(1-dynamicParameterB);

    dynamicFactorKv = ( ...
        (dynamicParameterA + ...
         sqrt(200*pitchLineVelocityMPerSec)) ./ ...
        dynamicParameterA).^dynamicParameterB;

    formFactorDrive = ...
        2.2 + 3.1*exp(-zDrive/14);

    formFactorDriven = ...
        2.2 + 3.1*exp(-zDriven/14);

    lewisFactorDrive = ...
        1 ./ (contactFactorKe .* formFactorDrive);

    lewisFactorDriven = ...
        1 ./ (contactFactorKe .* formFactorDriven);

    requiredWidthDriveMM = ...
        dynamicFactorKv .* tangentialForceN ./ ...
        (allowableStressDriveMPa .* ...
         moduleStageMM .* lewisFactorDrive);

    requiredWidthDrivenMM = ...
        dynamicFactorKv .* tangentialForceN ./ ...
        (allowableStressDrivenMPa .* ...
         moduleStageMM .* lewisFactorDriven);

    requiredStageWidthMM = max( ...
        [requiredWidthDriveMM;requiredWidthDrivenMM],[],1);

    criticalRole = repmat("Drivende",numberOfStages,1);
    drivenCritical = ...
        requiredWidthDrivenMM > requiredWidthDriveMM;
    criticalRole(drivenCritical(:)) = "Drevet";

    stressDriveMPa = ...
        NaN(1,numberOfStages);

    stressDrivenMPa = ...
        NaN(1,numberOfStages);

    safetyFactorDrive = ...
        NaN(1,numberOfStages);

    safetyFactorDriven = ...
        NaN(1,numberOfStages);

    widthProvided = ...
        isfinite(faceWidthStageMM);

    stressDriveMPa(widthProvided) = ...
        dynamicFactorKv(widthProvided) .* ...
        tangentialForceN(widthProvided) ./ ...
        (faceWidthStageMM(widthProvided) .* ...
         moduleStageMM(widthProvided) .* ...
         lewisFactorDrive(widthProvided));

    stressDrivenMPa(widthProvided) = ...
        dynamicFactorKv(widthProvided) .* ...
        tangentialForceN(widthProvided) ./ ...
        (faceWidthStageMM(widthProvided) .* ...
         moduleStageMM(widthProvided) .* ...
         lewisFactorDriven(widthProvided));

    safetyFactorDrive(widthProvided) = ...
        allowableStressDriveMPa(widthProvided) ./ ...
        stressDriveMPa(widthProvided);

    safetyFactorDriven(widthProvided) = ...
        allowableStressDrivenMPa(widthProvided) ./ ...
        stressDrivenMPa(widthProvided);

    stageWidthOK = ...
        false(1,numberOfStages);

    stageWidthOK(widthProvided) = ...
        faceWidthStageMM(widthProvided) >= ...
        requiredStageWidthMM(widthProvided)*(1-1e-12);

    selectedStandardWidthMM = ...
        NaN(1,numberOfStages);

    if ~isempty(availableStandardFaceWidthsMM)
        for k = 1:numberOfStages
            firstAdequateIndex = find( ...
                availableStandardFaceWidthsMM >= ...
                requiredStageWidthMM(k),1,'first');

            if ~isempty(firstAdequateIndex)
                selectedStandardWidthMM(k) = ...
                    availableStandardFaceWidthsMM(firstAdequateIndex);
            end
        end
    end

    gearStatusDrive = ...
        repmat("DIMENSIONER",numberOfStages,1);

    gearStatusDriven = ...
        repmat("DIMENSIONER",numberOfStages,1);

    gearStatusDrive(widthProvided(:) & ...
        stressDriveMPa(:) <= allowableStressDriveMPa(:)*(1+1e-12)) = ...
        "OK";

    gearStatusDrive(widthProvided(:) & ...
        stressDriveMPa(:) > allowableStressDriveMPa(:)*(1+1e-12)) = ...
        "IKKE OK";

    gearStatusDriven(widthProvided(:) & ...
        stressDrivenMPa(:) <= allowableStressDrivenMPa(:)*(1+1e-12)) = ...
        "OK";

    gearStatusDriven(widthProvided(:) & ...
        stressDrivenMPa(:) > allowableStressDrivenMPa(:)*(1+1e-12)) = ...
        "IKKE OK";

    stageStatus = ...
        repmat("DIMENSIONER",numberOfStages,1);

    stageStatus(widthProvided(:) & stageWidthOK(:)) = ...
        "OK";

    stageStatus(widthProvided(:) & ~stageWidthOK(:)) = ...
        "IKKE OK";

    allProvidedWidthsOK = ...
        all(stageWidthOK(widthProvided));

    if ~any(widthProvided)
        allProvidedWidthsOK = false;
    end

    out = struct;
    out.drivePitchDiameterMM = drivePitchDiameterMM;
    out.drivenPitchDiameterMM = drivenPitchDiameterMM;
    out.stageRatio = stageRatio;
    out.driveAddendumDiameterMM = driveAddendumDiameterMM;
    out.drivenAddendumDiameterMM = drivenAddendumDiameterMM;
    out.driveBaseDiameterMM = driveBaseDiameterMM;
    out.drivenBaseDiameterMM = drivenBaseDiameterMM;
    out.centerDistanceMM = centerDistanceMM;
    out.pathOfContactMM = pathOfContactMM;
    out.basePitchMM = basePitchMM;
    out.contactRatioCalculated = contactRatioCalculated;
    out.contactRatioUsed = contactRatioUsed;
    out.contactRatioSource = contactRatioSource;
    out.contactFactorKe = contactFactorKe;
    out.tangentialForceN = tangentialForceN;
    out.equivalentDriveTorqueNm = equivalentDriveTorqueNm;
    out.driveSpeedRPM = driveSpeedRPM;
    out.driveOmegaRadPerSec = driveOmegaRadPerSec;
    out.pitchLineVelocityMPerSec = pitchLineVelocityMPerSec;
    out.dynamicParameterA = dynamicParameterA;
    out.dynamicParameterB = dynamicParameterB;
    out.dynamicFactorKv = dynamicFactorKv;
    out.formFactorDrive = formFactorDrive;
    out.formFactorDriven = formFactorDriven;
    out.lewisFactorDrive = lewisFactorDrive;
    out.lewisFactorDriven = lewisFactorDriven;
    out.requiredWidthDriveMM = requiredWidthDriveMM;
    out.requiredWidthDrivenMM = requiredWidthDrivenMM;
    out.requiredStageWidthMM = requiredStageWidthMM;
    out.criticalRole = criticalRole;
    out.stressDriveMPa = stressDriveMPa;
    out.stressDrivenMPa = stressDrivenMPa;
    out.safetyFactorDrive = safetyFactorDrive;
    out.safetyFactorDriven = safetyFactorDriven;
    out.stageWidthOK = stageWidthOK;
    out.selectedStandardWidthMM = selectedStandardWidthMM;
    out.gearStatusDrive = gearStatusDrive;
    out.gearStatusDriven = gearStatusDriven;
    out.stageStatus = stageStatus;
    out.allProvidedWidthsOK = allProvidedWidthsOK;
    out.allContactRatiosOK = ...
        all(contactRatioUsed >= minimumContactRatio);
end
