%% T3 - TANDFODSSPAENDING OG NOEDVENDIG TANDBREDDE
% Rettelse 2026-06-18: robuste tabeldimensioner for baade ét og flere trin.
% Brug dette script naar en opgave omhandler et eller flere standard,
% ligefortandede, udvendige evolvent-tandhjulspar og spoerger efter:
% - boejningsspaending i tandfoden
% - noedvendig faelles tandbredde for et tandhjulspar
% - hvilket hjul der er kritisk
%
% Brug ikke dette script til:
% - skraafortanding, profilforskydning eller indvendige tandhjul
% - tandflanketryk/pitting
% - fuld AGMA/ISO-beregning med faktorer, som ikke indgaar i kursets
%   reducerede metode
% - bestemmelse af tandkraft uden at moment eller Wt er kendt
%
% Kursusmetode:
%   sigma = Kv*Wt/(b*m*Y)
%   Y     = 1/(Ke*KF)
%   Ke    = 1/mc
%   KF    = 2.2 + 3.1*exp(-N/14)
%
% Den dynamiske faktor beregnes som:
%   Kv = ((A + sqrt(200*V))/A)^B
%   A  = 50 + 56*(1-B)
%   B  = 0.25*(12-Qv)^(2/3)
%
% Modeller/opslag manuelt foerst:
% 1) Fastlaeg den tangentiale tandkraft Wt eller det drivende moment.
% 2) Fastlaeg hastigheden paa det drivende hjul eller periferihastigheden.
% 3) Angiv den tilladelige tandfodsspaending for hvert materiale.
% 4) Angiv eventuelle tilgaengelige standardbredder. Scriptet opfinder
%    ikke standardmaal.
%
% Kursusgrundlag:
% - Eksempeleksamen, problem 1 og formelsamlingen.
% - TANDHJUL_FRL.pdf, afsnittet om tandfodsbrud og dynamisk faktor.
% - TANDHJUL_OPGAVE_LOSN.pdf, styrkeundersoegelse af tandhjul.

clear; clc; close all;

%% ASSUMPTIONS AND MANUAL INPUT
% - Standard, ligefortandede, udvendige tandhjul uden profilforskydning.
% - Samme modul, indgrebsvinkel og tandbredde for hjulene i hvert par.
% - Wt er den samme kraftstoerrelse paa begge hjul i et indgreb.
% - Kursusformlen anvendes i N, mm og MPa:
%       1 MPa = 1 N/mm^2
% - Kv er faelles for de to hjul i samme indgreb.
% - Indgrebsgraden kan beregnes fra standardgeometrien eller indtastes
%   manuelt fra T1.
% - Kraft-, moment- og hastighedsinput skal hoere til det drivende hjul.
% - Spaendingen er en dynamisk, nominel tandfodsspaending efter den
%   reducerede kursusmetode. Lokale effekter uden for metoden er ikke
%   automatisk inkluderet.

%% INPUT
