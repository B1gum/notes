if strcmpi(speedInputMode, "rpm")
    assert(all(isfinite(driveSpeedRPM)) && all(driveSpeedRPM > 0), ...
        'driveSpeedRPM skal vaere positiv for alle trin.');
else
    assert(all(isfinite(pitchLineVelocityMPerSec)) && ...
           all(pitchLineVelocityMPerSec >= 0), ...
        'pitchLineVelocityMPerSec skal vaere ikke-negativ.');
end

if strcmpi(contactRatioMode, "manual")
    assert(all(isfinite(manualContactRatio)) && ...
           all(manualContactRatio > 0), ...
        'manualContactRatio skal vaere positiv for alle trin.');
end

assert(all(isfinite(allowableStressDriveMPa)) && ...
       all(allowableStressDriveMPa > 0) && ...
       all(isfinite(allowableStressDrivenMPa)) && ...
       all(allowableStressDrivenMPa > 0), ...
    'Tilladelige spaendinger skal vaere positive [MPa].');

assert(all(isnan(faceWidthStageMM) | ...
       (isfinite(faceWidthStageMM) & faceWidthStageMM > 0)), ...
    'faceWidthStageMM skal vaere positiv [mm] eller NaN.');

assert(isfinite(minimumContactRatio) && minimumContactRatio > 0, ...
