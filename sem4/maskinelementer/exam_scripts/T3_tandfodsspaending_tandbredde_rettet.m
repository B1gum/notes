%% AUTOMATIC CHECKS
allChecksOK = true;

for k = 1:numberOfStages
    if calculation.contactRatioUsed(k) >= minimumContactRatio
        fprintf('OK - trin %d: indgrebsgrad %.3f >= %.2f.\n', ...
            k,calculation.contactRatioUsed(k),minimumContactRatio);
    else
        fprintf('IKKE OK - trin %d: indgrebsgrad %.3f < %.2f.\n', ...
            k,calculation.contactRatioUsed(k),minimumContactRatio);
        allChecksOK = false;
    end

    if strcmpi(contactRatioMode,"manual")
        relativeContactDifference = abs( ...
            calculation.contactRatioUsed(k) - ...
            calculation.contactRatioCalculated(k)) / ...
            calculation.contactRatioCalculated(k);

        if relativeContactDifference > 0.01
            fprintf(['ADVARSEL - trin %d: manuelt mc afviger %.2f %% ', ...
                'fra standardgeometrien. Det kan vaere korrekt ved ', ...
                'anden geometri, men skal begrundes.\n'], ...
                k,100*relativeContactDifference);
        end
    end

    if isnan(faceWidthStageMM(k))
        fprintf(['ADVARSEL - trin %d: ingen faktisk tandbredde er ', ...
            'angivet; kun breddekravet er beregnet.\n'],k);
    elseif calculation.stageWidthOK(k)
        fprintf(['OK - trin %d: b = %.3f mm >= b_kraevet = ', ...
            '%.3f mm.\n'], ...
            k,faceWidthStageMM(k), ...
            calculation.requiredStageWidthMM(k));
    else
        fprintf(['IKKE OK - trin %d: b = %.3f mm < b_kraevet = ', ...
            '%.3f mm.\n'], ...
            k,faceWidthStageMM(k), ...
            calculation.requiredStageWidthMM(k));
        allChecksOK = false;
    end

    if ~isempty(availableStandardFaceWidthsMM) && ...
            isnan(calculation.selectedStandardWidthMM(k))
        fprintf(['ADVARSEL - trin %d: ingen leveret standardbredde ', ...
            'opfylder det kontinuerlige breddekrav.\n'],k);
    end
end

forceReconstructionErrorN = max(abs( ...
    calculation.tangentialForceN - ...
    2*calculation.equivalentDriveTorqueNm*1000 ./ ...
    calculation.drivePitchDiameterMM));

if forceReconstructionErrorN <= ...
        1e-10*max(1,max(calculation.tangentialForceN))
    fprintf('OK - Wt = 2*T/d er enhedskonsistent.\n');
else
    fprintf('IKKE OK - inkonsistens mellem Wt, T og d.\n');
    allChecksOK = false;
end

if all(calculation.dynamicFactorKv >= 1-1e-12)
    fprintf('OK - alle dynamiske faktorer Kv er mindst 1.\n');
else
    fprintf('IKKE OK - mindst én dynamisk faktor er under 1.\n');
    allChecksOK = false;
end

results.allAutomaticChecksOK = allChecksOK;

%% PLOTS
if makeWidthSweepPlot
    allRequiredWidths = [ ...
        calculation.requiredWidthDriveMM; ...
        calculation.requiredWidthDrivenMM];

    [~,criticalLinearIndex] = max(allRequiredWidths(:));

    [criticalRoleRow,criticalStage] = ...
        ind2sub(size(allRequiredWidths),criticalLinearIndex);

    if criticalRoleRow == 1
        criticalRoleText = "drivende";
        criticalY = calculation.lewisFactorDrive(criticalStage);
        criticalAllowableMPa = ...
            allowableStressDriveMPa(criticalStage);
    else
        criticalRoleText = "drevet";
        criticalY = calculation.lewisFactorDriven(criticalStage);
        criticalAllowableMPa = ...
            allowableStressDrivenMPa(criticalStage);
    end

    criticalRequiredWidthMM = ...
        allRequiredWidths(criticalRoleRow,criticalStage);

    widthSweepMM = linspace( ...
        max(0.25*criticalRequiredWidthMM,0.1), ...
        2.0*criticalRequiredWidthMM, ...
        250);

    stressSweepMPa = ...
        calculation.dynamicFactorKv(criticalStage) * ...
        calculation.tangentialForceN(criticalStage) ./ ...
        (widthSweepMM * moduleStageMM(criticalStage) * criticalY);

    figure('Name','T3 - tandbredde og tandfodsspaending');

    plot(widthSweepMM,stressSweepMPa,'LineWidth',1.2);
    hold on
    yline(criticalAllowableMPa,'--','Tilladt spaending');
    xline(criticalRequiredWidthMM,'--','Kraevet bredde');

    if ~isnan(faceWidthStageMM(criticalStage))
        actualStressMPa = ...
            calculation.dynamicFactorKv(criticalStage) * ...
            calculation.tangentialForceN(criticalStage) / ...
            (faceWidthStageMM(criticalStage) * ...
             moduleStageMM(criticalStage) * criticalY);

        plot(faceWidthStageMM(criticalStage),actualStressMPa,'o', ...
            'MarkerSize',7,'LineWidth',1.2);
    end

    hold off
    grid on

    xlabel('Tandbredde b [mm]');
    ylabel('Dynamisk tandfodsspaending [MPa]');

    title(sprintf( ...
        'Kritisk hjul: trin %d, %s', ...
        criticalStage,char(criticalRoleText)));

    legend('Beregnet spaending','Location','best');
end

