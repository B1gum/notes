availableStandardFaceWidthsMM = []; % [mm] fx [20 25 30 35], kun hvis opgivet

% Plot og indbyggede test
makeWidthSweepPlot = true;         % [-] true giver bredde-spaendingsplot
runCourseRegressionTests = true;   % [-] test mod kursusopgaver

