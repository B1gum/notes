assert(numberOfStages >= 1, ...
    'Der skal vaere mindst ét tandhjulsindgreb.');

assert(numel(zDriven) == numberOfStages && ...
       numel(moduleStageMM) == numberOfStages && ...
       numel(pressureAngleDeg) == numberOfStages && ...
       numel(qualityNumberQv) == numberOfStages, ...
    ['zDrive, zDriven, moduleStageMM, pressureAngleDeg og ', ...
     'qualityNumberQv skal have samme laengde.']);

assert(numel(driveTorqueNm) == numberOfStages && ...
       numel(tangentialForceN) == numberOfStages && ...
       numel(driveSpeedRPM) == numberOfStages && ...
       numel(pitchLineVelocityMPerSec) == numberOfStages && ...
       numel(manualContactRatio) == numberOfStages && ...
       numel(allowableStressDriveMPa) == numberOfStages && ...
       numel(allowableStressDrivenMPa) == numberOfStages && ...
       numel(faceWidthStageMM) == numberOfStages, ...
    'Alle trinvise input skal have ét element pr. indgreb.');

assert(all(isfinite(zDrive)) && all(isfinite(zDriven)) && ...
       all(zDrive > 0) && all(zDriven > 0) && ...
       all(mod(zDrive,1) == 0) && all(mod(zDriven,1) == 0), ...
    'Tandtallene skal vaere positive heltal.');

assert(all(isfinite(moduleStageMM)) && all(moduleStageMM > 0), ...
    'Modulerne skal vaere positive [mm].');

assert(all(isfinite(pressureAngleDeg)) && ...
       all(pressureAngleDeg > 0 & pressureAngleDeg < 90), ...
    'Indgrebsvinklerne skal ligge mellem 0 og 90 deg.');

assert(all(isfinite(qualityNumberQv)) && ...
       all(qualityNumberQv >= 3 & qualityNumberQv <= 12), ...
    'Kursusformlen for Kv anvendes for Qv i intervallet 3...12.');

assert(any(strcmpi(loadInputMode, ["torque","force"])), ...
    'loadInputMode skal vaere "torque" eller "force".');

assert(any(strcmpi(speedInputMode, ["rpm","velocity"])), ...
    'speedInputMode skal vaere "rpm" eller "velocity".');

assert(any(strcmpi(contactRatioMode, ["calculate","manual"])), ...
    'contactRatioMode skal vaere "calculate" eller "manual".');

